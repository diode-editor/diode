import * as fs from "node:fs";

/**
 * Сносит временный каталог теста, не роняя прогон, но и не молча.
 *
 * Снести не удаётся, когда в каталог ещё кто-то пишет (живой субпроцесс,
 * отложенная запись) — и это ровно тот случай, который годами копил мусор в
 * `os.tmpdir()`: ошибка глушилась пустым `catch`, каталог оставался, и никто не
 * знал. Падать тут нечестно (прогон уже прошёл, каталог временный), поэтому
 * ошибка уходит в предупреждение — его видно в выводе прогона.
 *
 * `label` — чей это каталог, чтобы предупреждение было адресным.
 */
export function removeDirLoud(dir: string, label: string): void {
    try {
        fs.rmSync(dir, { recursive: true, force: true });
    } catch (err) {
        console.warn(`[${label}] не удалось снести временный каталог ${dir}:`, err);
    }
}
