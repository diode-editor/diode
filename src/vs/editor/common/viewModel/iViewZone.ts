/**
 * View zone — вставные виртуальные строки между строками документа (аналог
 * `IViewZone` VS Code, только высота в строках — терминал не знает пикселей).
 *
 * Зоны — свойство ВЬЮ, а не документа: документных строк они не занимают,
 * позиции каретки/выделений остаются документными, каретка на зоне стоять не
 * может by construction. Главный потребитель — дифф из двух настоящих
 * редакторов: зоны-филлеры выравнивают стороны напротив односторонних правок
 * (docs/TODO/DiffEditable.md).
 */
export interface IViewZone {
    /**
     * Документная строка (0-based), ПОСЛЕ которой вставляются виртуальные
     * строки; `-1` — перед первой строкой файла (аналог upstream-конвенции
     * `afterLineNumber: 0` в 1-based координатах).
     */
    readonly afterLine: number;
    /** Сколько виртуальных строк вставить (> 0). */
    readonly size: number;
}

/** Вид строки вью: документная, виртуальная (зона) или за концом вью. */
export type ViewLineKind = "doc" | "zone" | "none";
