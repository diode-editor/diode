#!/usr/bin/env node
/**
 * Generates `src/vs/base/common/codicons.generated.ts`, the "codicon name → font
 * glyph" table from upstream. Private Use Area codepoints cannot be derived, only taken
 * from upstream, and a hand-made copy goes stale on the first pin update.
 *
 * Sources: `codiconsLibrary.ts` (the table) and `codicons.ts` (`codiconsDerived`: some
 * entries refer to a library name rather than a codepoint).
 *
 * The pin moves in lockstep with `extensions/VSCODE_VERSION` and `scripts/import-vscode-dts.mjs`.
 *
 *   (no flags) — regenerate (git clone, needs network);
 *   --check    — compare the file with a fresh generation, exit 1 on drift.
 *
 * Usage: node scripts/import-codicons.mjs [--check]
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const VSCODE_TAG = "1.127.0";
const VSCODE_REPO = "https://github.com/microsoft/vscode.git";
const LIBRARY_PATH = "src/vs/base/common/codiconsLibrary.ts";
const DERIVED_PATH = "src/vs/base/common/codicons.ts";

const repoRoot = resolve(import.meta.dirname, "..");
const targetFile = resolve(repoRoot, "src", "vs", "base", "common", "codicons.generated.ts");

function fetchUpstream() {
    const scratch = mkdtempSync(join(tmpdir(), "vscode-codicons-"));
    const cloneDir = join(scratch, "vscode");
    try {
        console.error(`[codicons] cloning microsoft/vscode@${VSCODE_TAG} (sparse, blobless)`);
        execFileSync(
            "git",
            [
                "clone",
                "--depth",
                "1",
                "--filter=blob:none",
                "--sparse",
                "--branch",
                VSCODE_TAG,
                VSCODE_REPO,
                cloneDir,
            ],
            { stdio: ["ignore", "ignore", "inherit"] },
        );
        execFileSync("git", ["-C", cloneDir, "sparse-checkout", "set", "--no-cone", LIBRARY_PATH, DERIVED_PATH], {
            stdio: ["ignore", "ignore", "inherit"],
        });
        const commit = execFileSync("git", ["-C", cloneDir, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
        return {
            commit,
            library: readFileSync(join(cloneDir, LIBRARY_PATH), "utf8"),
            derived: readFileSync(join(cloneDir, DERIVED_PATH), "utf8"),
        };
    } finally {
        rmSync(scratch, { recursive: true, force: true });
    }
}

/**
 * `register('<name>', 0x<codepoint> | '<other name>')` in order: a reference by name
 * resolves to an already parsed codepoint, like upstream `codiconsUtil.register`.
 */
function parseRegistrations(source, into) {
    const re = /register\(\s*'([a-z0-9-]+)'\s*,\s*(0x[0-9a-fA-F]+|'[a-z0-9-]+')\s*\)/gu;
    for (const match of source.matchAll(re)) {
        const [, name, value] = match;
        if (value.startsWith("0x")) {
            into.set(name, Number.parseInt(value, 16));
            continue;
        }
        const referenced = into.get(value.slice(1, -1));
        if (referenced === undefined) {
            throw new Error(`[codicons] ${name} refers to unknown codicon ${value}`);
        }
        into.set(name, referenced);
    }
}

function render(entries, commit) {
    const lines = [
        "// VS Code codicon table: name → font glyph.",
        "//",
        `// Generated by scripts/import-codicons.mjs from microsoft/vscode@${VSCODE_TAG}`,
        `// (commit ${commit}), files src/vs/base/common/codicons{,Library}.ts.`,
        "// Do not edit by hand — change the generator and rerun it.",
        "//",
        "// The glyphs live in the Unicode Private Use Area: only a font with",
        "// codicons (a nerd font) draws them, like the rest of Diode's UI glyphs.",
        "",
        "/** Codicon name (`$(check)`) → font glyph; an unknown name gives `undefined`. */",
        "export const CODICON_GLYPHS: Readonly<Partial<Record<string, string>>> = {",
    ];
    for (const [name, codepoint] of entries) {
        const escaped = `\\u${codepoint.toString(16).padStart(4, "0")}`;
        // As prettier would quote it (quoteProps: as-needed).
        const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(name) ? name : JSON.stringify(name);
        lines.push(`    ${key}: "${escaped}",`);
    }
    lines.push("};", "");
    return lines.join("\n");
}

const upstream = fetchUpstream();
const registrations = new Map();
parseRegistrations(upstream.library, registrations);
parseRegistrations(upstream.derived, registrations);
if (registrations.size === 0) throw new Error("[codicons] upstream yielded no entries: did the format change?");

const generated = render([...registrations].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)), upstream.commit);

if (process.argv.includes("--check")) {
    const current = readFileSync(targetFile, "utf8");
    if (current !== generated) {
        console.error("[codicons] drift: src/vs/base/common/codicons.generated.ts differs from the upstream table");
        process.exit(1);
    }
    console.error(`[codicons] ok: ${registrations.size} entries match upstream@${VSCODE_TAG}`);
} else {
    writeFileSync(targetFile, generated);
    console.error(`[codicons] wrote ${registrations.size} entries to ${targetFile}`);
}
